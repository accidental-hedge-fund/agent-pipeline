export interface ChangelogRelease {
  /** Semver without leading v, e.g. "1.29.1". */
  version: string;
  /** ISO date YYYY-MM-DD when known. */
  date?: string;
  /** Tag subject / release title body. */
  subject?: string;
  /** Optional longer release body (GitHub Release notes). */
  body?: string;
}

export interface ChangelogDeps {
  /** List releases newest-first or any order; generator sorts. */
  listReleases: () => ChangelogRelease[] | Promise<ChangelogRelease[]>;
}

/**
 * Pure transform: releases → CHANGELOG.md (Keep a Changelog-ish headings).
 */
export function renderChangelogMarkdown(releases: ChangelogRelease[]): string {
  const sorted = [...releases].sort((a, b) => compareSemverDesc(a.version, b.version));
  const lines: string[] = [
    "# Changelog",
    "",
    GENERATED_BANNER,
    "",
    "Release history generated from git tags (and optional GitHub Release bodies).",
    "GitHub milestones own planned release membership; [ROADMAP.md](ROADMAP.md) is human-readable forward documentation.",
    "",
    "Regenerate with `node scripts/generate-docs.mjs` (or `npm run docs:generate`).",
    "",
  ];

  for (const rel of sorted) {
    const ver = rel.version.replace(/^v/, "");
    const datePart = rel.date ? ` - ${rel.date}` : "";
    lines.push(`## [${ver}]${datePart}`, "");
    const subject = (rel.subject ?? "").trim();
    const body = (rel.body ?? "").trim();
    if (subject) {
      // Avoid duplicating "vX.Y.Z —" prefixes when the tag subject already has them.
      const cleaned = subject
        .replace(new RegExp(`^v?${escapeRegExp(ver)}\\s*[—–-]\\s*`), "")
        .replace(/^release:\\s*/i, "")
        .trim();
      if (cleaned) lines.push(cleaned, "");
    }
    if (body && body !== subject) {
      lines.push(body, "");
    }
    if (!subject && !body) {
      lines.push(`Tag \`v${ver}\`.`, "");
    }
  }

  if (sorted.length === 0) {
    lines.push("_No version tags found._", "");
  }

  return normalizeTrailingNewline(lines.join("\n"));
}

function escapeRegExp(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

/** Compare semver strings descending (newest first). Non-numeric tails sort last. */
export function compareSemverDesc(a: string, b: string): number {
  const pa = parseSemver(a);
  const pb = parseSemver(b);
  for (let i = 0; i < 3; i++) {
    if (pa[i] !== pb[i]) return pb[i] - pa[i];
  }
  return 0;
}

function parseSemver(v: string): [number, number, number] {
  const m = v.replace(/^v/, "").match(/^(\d+)\.(\d+)\.(\d+)/);
  if (!m) return [0, 0, 0];
  return [Number(m[1]), Number(m[2]), Number(m[3])];
}

/**
 * Default git-tag reader for CHANGELOG generation. Injectable for tests via deps.
 * Parses `git tag -l --format=...` output lines: `tag|date|subject`.
 */
export function parseGitTagListLines(stdout: string): ChangelogRelease[] {
  const releases: ChangelogRelease[] = [];
  for (const line of stdout.split(/\r?\n/)) {
    if (!line.trim()) continue;
    const [tag, date, ...rest] = line.split("|");
    if (!tag) continue;
    const m = tag.trim().match(/^v(\d+\.\d+\.\d+)$/);
    if (!m) continue;
    releases.push({
      version: m[1]!,
      date: date?.trim() || undefined,
      subject: rest.join("|").trim() || undefined,
    });
  }
  return releases;
}

// ---------------------------------------------------------------------------
// Artifact set (for generate-docs.mjs)
// ---------------------------------------------------------------------------

export type GeneratedArtifact = {
  /** Path relative to repo root. */
  relPath: string;
  /** Full file contents after generation. */
  content: string;
};

export interface BuildArtifactsInput {
  skillClaude?: string;
  skillCodex?: string;
  skillOmp?: string;
  skillOpencode?: string;
  configSchema: JsonSchemaNode;
  configDefaults?: Record<string, unknown>;
  changelogReleases: ChangelogRelease[];
  registry?: Record<string, unknown>;
  docs?: Record<string, CommandDoc>;
  operationSurface?: readonly OperationSurfaceEntry[];
}

/**
 * Build the full set of generator-owned artifacts (pure).
 * SKILL paths are only included when source text is provided.
 */
export function buildGeneratedArtifacts(input: BuildArtifactsInput): GeneratedArtifact[] {
  const artifacts: GeneratedArtifact[] = [
    {
      relPath: "docs/cli.md",
      content: renderCliMarkdown({
        registry: input.registry,
        docs: input.docs,
        operationSurface: input.operationSurface,
      }),
    },
    {
      relPath: "docs/config.md",
      content: renderConfigMarkdown({
        schema: input.configSchema,
        defaults: input.configDefaults,
      }),
    },
    {
      relPath: "CHANGELOG.md",
      content: renderChangelogMarkdown(input.changelogReleases),
    },
  ];

  const hostSkills = [
    { relPath: "hosts/claude/SKILL.md", source: input.skillClaude, token: "/pipeline" },
    { relPath: "hosts/codex/SKILL.md", source: input.skillCodex, token: "$pipeline" },
    { relPath: "hosts/omp/SKILL.md", source: input.skillOmp, token: "/pipeline" },
    { relPath: "hosts/opencode/SKILL.md", source: input.skillOpencode, token: "/pipeline" },
  ];
  for (const host of hostSkills) {
    if (host.source === undefined) continue;
    artifacts.push({
      relPath: host.relPath,
      content: normalizeTrailingNewline(
        applySkillCommandTable(host.source, host.token, {
          registry: input.registry,
          docs: input.docs,
          operationSurface: input.operationSurface,
        }),
      ),
    });
  }

  return artifacts;
}
