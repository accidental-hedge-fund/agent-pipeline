export type JsonSchemaNode = {
  type?: string | string[];
  description?: string;
  enum?: unknown[];
  properties?: Record<string, JsonSchemaNode>;
  items?: JsonSchemaNode;
  anyOf?: JsonSchemaNode[];
  oneOf?: JsonSchemaNode[];
  $ref?: string;
  minimum?: number;
  maximum?: number;
  exclusiveMinimum?: number | boolean;
  exclusiveMaximum?: number | boolean;
  minLength?: number;
  additionalProperties?: boolean | JsonSchemaNode;
  [key: string]: unknown;
};

export interface RenderConfigOptions {
  schema: JsonSchemaNode;
  /** Optional defaults map (e.g. DEFAULT_CONFIG); dotted paths not required. */
  defaults?: Record<string, unknown>;
}

/**
 * Emit docs/config.md from a JSON Schema object derived from PartialConfigSchema.
 * Omits keys the schema does not list (e.g. auto_merge is never a property).
 */
export function renderConfigMarkdown(opts: RenderConfigOptions): string {
  const props = opts.schema.properties ?? {};
  const lines: string[] = [
    "# Config reference",
    "",
    GENERATED_BANNER,
    "",
    "Generated from the Zod `PartialConfigSchema` surface in `core/scripts/config.ts`",
    "(via `generateConfigSchema()` / `pipeline config schema`). Commit",
    "`.github/pipeline.yml` to override defaults. Keys rejected by the schema",
    "(for example `auto_merge`) are **not** documented here.",
    "Merge authority is not repository configuration and cannot be set here.",
    "",
    "Regenerate with `node scripts/generate-docs.mjs` (or `npm run docs:generate`).",
    "",
    "## Top-level keys",
    "",
  ];

  const keys = Object.keys(props).sort((a, b) => a.localeCompare(b));
  for (const key of keys) {
    const node = props[key]!;
    lines.push(...renderConfigKey(key, node, opts.defaults?.[key], 0));
  }

  lines.push(
    "## Notes",
    "",
    "- Descriptions come from Zod `.describe()` annotations on the schema.",
    "- Nested objects expand one level of children when present.",
    "- For machine-readable validation, use `pipeline config schema` and",
    "  `pipeline config validate`.",
    "",
  );
  return normalizeTrailingNewline(lines.join("\n"));
}

function renderConfigKey(
  name: string,
  node: JsonSchemaNode,
  defaultValue: unknown,
  depth: number,
): string[] {
  const indent = "";
  const headingLevel = depth === 0 ? "###" : "####";
  const typeStr = describeType(node);
  const desc = (node.description ?? "").trim() || "(no description)";
  const lines: string[] = [
    `${headingLevel} \`${name}\``,
    "",
    `- **Type:** ${typeStr}`,
  ];
  if (defaultValue !== undefined) {
    lines.push(`- **Default:** \`${formatDefault(defaultValue)}\``);
  }
  lines.push(`- **Description:** ${desc}`, "");

  if (node.enum && node.enum.length > 0) {
    lines.push(`- **Allowed values:** ${node.enum.map((v) => `\`${String(v)}\``).join(", ")}`, "");
  }

  const childProps = node.properties;
  if (childProps && depth < 1) {
    const childKeys = Object.keys(childProps).sort((a, b) => a.localeCompare(b));
    if (childKeys.length > 0) {
      lines.push("Nested fields:", "");
      for (const ck of childKeys) {
        lines.push(...renderConfigKey(`${name}.${ck}`, childProps[ck]!, undefined, depth + 1));
      }
    }
  }
  return lines;
}

function describeType(node: JsonSchemaNode): string {
  if (node.enum) return `enum`;
  if (node.type) {
    if (Array.isArray(node.type)) return node.type.join(" | ");
    if (node.type === "array" && node.items) {
      return `array of ${describeType(node.items)}`;
    }
    if (node.type === "object" && node.properties) return "object";
    return String(node.type);
  }
  if (node.anyOf) return node.anyOf.map(describeType).join(" | ");
  if (node.oneOf) return node.oneOf.map(describeType).join(" | ");
  return "unknown";
}

function formatDefault(value: unknown): string {
  if (typeof value === "string") return value;
  try {
    return JSON.stringify(value);
  } catch {
    return String(value);
  }
}

