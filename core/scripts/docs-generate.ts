// Pure docs generators for CLI reference, config reference, SKILL tables, and
// CHANGELOG (#597). Unit-tested without network/git/subprocess; live I/O is
// injected via deps at the scripts/generate-docs.mjs boundary.

import {
  formatHostUsage,
  listDocumentedCommands,
  type CommandDoc,
  type DocumentedCommand,
} from "./command-docs.ts";
import { COMMAND_REGISTRY } from "./command-registry.ts";
import type { OperationSurfaceEntry } from "./operation-surface.ts";

// ---------------------------------------------------------------------------
// Shared helpers
// ---------------------------------------------------------------------------

export const CLI_BEGIN_MARKER = "<!-- BEGIN GENERATED: cli-command-table -->";
export const CLI_END_MARKER = "<!-- END GENERATED: cli-command-table -->";

export const GENERATED_BANNER =
  "<!-- Generated by scripts/generate-docs.mjs — do not edit by hand. -->";

/** Normalize trailing newlines for stable comparisons. */
export function normalizeTrailingNewline(text: string): string {
  return text.replace(/\s*$/, "\n");
}

/**
 * Replace the region between stable begin/end markers (exclusive of markers).
 * Throws when markers are missing or mis-ordered.
 */
export function replaceMarkedRegion(
  source: string,
  beginMarker: string,
  endMarker: string,
  body: string,
): string {
  const beginIdx = source.indexOf(beginMarker);
  const endIdx = source.indexOf(endMarker);
  if (beginIdx === -1 || endIdx === -1 || endIdx <= beginIdx) {
    throw new Error(
      `docs-generate: markers not found or mis-ordered (${beginMarker} / ${endMarker})`,
    );
  }
  const before = source.slice(0, beginIdx + beginMarker.length);
  const after = source.slice(endIdx);
  const inner = body.endsWith("\n") ? body : `${body}\n`;
  return `${before}\n${inner}${after}`;
}

