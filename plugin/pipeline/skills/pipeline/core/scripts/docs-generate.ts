/** Minimal JSON Schema node shape we walk for docs. */
export interface JsonSchemaNode {
  type?: string | string[];
  description?: string;
  enum?: unknown[];
  properties?: Record<string, JsonSchemaNode>;
  items?: JsonSchemaNode | JsonSchemaNode[];
  anyOf?: JsonSchemaNode[];
  oneOf?: JsonSchemaNode[];
  $ref?: string;
  additionalProperties?: boolean | JsonSchemaNode;
  [key: string]: unknown;
}

function unwrapSchema(node: JsonSchemaNode | undefined): JsonSchemaNode | undefined {
  if (!node) return undefined;
  // zod-to-json-schema often wraps optionals as anyOf: [T, {type:null}] or similar.
  if (Array.isArray(node.anyOf)) {
    const nonNull = node.anyOf.find((n) => n && n.type !== "null" && (n as { const?: unknown }).const === undefined);
    if (nonNull) return { ...nonNull, description: node.description ?? nonNull.description };
  }
  if (Array.isArray(node.oneOf)) {
    const nonNull = node.oneOf.find((n) => n && n.type !== "null");
    if (nonNull) return { ...nonNull, description: node.description ?? nonNull.description };
  }
  return node;
}

function typeLabel(node: JsonSchemaNode | undefined): string {
  if (!node) return "unknown";
  const n = unwrapSchema(node) ?? node;
  if (Array.isArray(n.enum) && n.enum.length > 0) {
    return `enum: ${n.enum.map((v) => JSON.stringify(v)).join(" | ")}`;
  }
  if (n.type === "array" || (Array.isArray(n.type) && n.type.includes("array"))) {
    const items = Array.isArray(n.items) ? n.items[0] : n.items;
    const inner = typeLabel(items as JsonSchemaNode | undefined);
    return `array of ${inner}`;
  }
  if (n.type === "object" || n.properties) return "object";
  if (Array.isArray(n.type)) return n.type.filter((t) => t !== "null").join(" | ") || "unknown";
  if (typeof n.type === "string") return n.type;
  if (n.properties) return "object";
  return "unknown";
}

function renderConfigField(
  name: string,
  node: JsonSchemaNode,
  depth: number,
): string[] {
  const n = unwrapSchema(node) ?? node;
  const heading = "#".repeat(Math.min(depth, 6));
  const lines: string[] = [];
  lines.push(`${heading} \`${name}\``);
  lines.push("");
  const desc = (n.description ?? node.description ?? "").trim();
  if (desc) lines.push(desc, "");
  lines.push(`- **Type:** \`${typeLabel(node)}\``);
  if (Array.isArray(n.enum) && n.enum.length > 0) {
    lines.push(`- **Allowed values:** ${n.enum.map((v) => `\`${JSON.stringify(v)}\``).join(", ")}`);
  }
  lines.push("");

  const props = n.properties;
  if (props && typeof props === "object") {
    for (const [child, childNode] of Object.entries(props)) {
      lines.push(...renderConfigField(`${name}.${child}`, childNode, depth + 1));
    }
  }
  return lines;
}

/**
 * Render docs/config.md from a JSON Schema object (typically generateConfigSchema()).
 * Explicitly never documents `auto_merge` even if somehow present.
 */
export function renderConfigReferenceMarkdown(schema: JsonSchemaNode): string {
  const props = schema.properties ?? {};
  const lines: string[] = [
    "# Config reference",
    "",
    GENERATED_BANNER,
    "",
    "Generated from `PartialConfigSchema` in `core/scripts/config.ts` via `generateConfigSchema()`.",
    "Commit a `.github/pipeline.yml` to override defaults. Keys are optional unless noted;",
    "unknown top-level keys are rejected (strict schema).",
    "",
    "There is **no** `auto_merge` configuration key. The pipeline never merges autonomously.",
    "",
    "## Top-level keys",
    "",
  ];

  const names = Object.keys(props).sort();
  for (const name of names) {
    if (name === "auto_merge") continue;
    lines.push(...renderConfigField(name, props[name]!, 3));
  }

  // Guard: if auto_merge somehow appeared, we already skipped it; also assert in tests.
  return normalizeNewlines(lines.join("\n"));
}

