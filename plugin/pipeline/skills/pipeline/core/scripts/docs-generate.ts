export interface ChangelogRelease {
  /** Semver without leading v, e.g. "1.28.4" */
  version: string;
  /** ISO date YYYY-MM-DD when known */
  date?: string;
  /** Tag subject / release body (already plain text) */
  body: string;
}

export interface ChangelogDeps {
  /** Return releases newest-first. Tests inject fixtures; CLI uses git tags. */
  listReleases: () => ChangelogRelease[];
}

/**
 * Pure transform: releases → CHANGELOG.md body (Keep a Changelog-ish).
 */
export function renderChangelogMarkdown(releases: ChangelogRelease[]): string {
  const lines: string[] = [
    "# Changelog",
    "",
    GENERATED_BANNER,
    "",
    "Historical release notes derived from git tags (and optional release bodies).",
    "Forward-looking planning lives in [`ROADMAP.md`](./ROADMAP.md).",
    "",
  ];

  // Newest first
  const sorted = [...releases].sort((a, b) => compareSemverDesc(a.version, b.version));
  for (const rel of sorted) {
    const datePart = rel.date ? ` - ${rel.date}` : "";
    lines.push(`## [${rel.version}]${datePart}`, "");
    const body = (rel.body ?? "").trim();
    if (body) {
      // Prefer the release summary bullets; drop release-PR ceremony that tags
      // often carry verbatim from `pipeline release` PR bodies.
      let cleaned = body
        .replace(/^#+\s*v?[\d.]+\s*[—\-:].*\n+/m, "")
        .replace(/^\*\*Shipped[^*]*\*\*\s*/m, "")
        .replace(/\n*---+\s*\n+[\s\S]*$/m, "") // drop everything after a horizontal rule (merge/token notes)
        .replace(/\n*_Prepared by `pipeline release`_[\s\S]*$/m, "")
        .replace(/\n*\*\*Merging this PR is the final step\.\*\*[\s\S]*$/m, "")
        .trim();
      lines.push(cleaned || "_(no tag body)_", "");
    } else {
      lines.push("_(no tag body)_", "");
    }
  }

  return normalizeNewlines(lines.join("\n"));
}

function compareSemverDesc(a: string, b: string): number {
  const pa = a.replace(/^v/, "").split(".").map((x) => parseInt(x, 10) || 0);
  const pb = b.replace(/^v/, "").split(".").map((x) => parseInt(x, 10) || 0);
  for (let i = 0; i < 3; i++) {
    const d = (pb[i] ?? 0) - (pa[i] ?? 0);
    if (d !== 0) return d;
  }
  return 0;
}

