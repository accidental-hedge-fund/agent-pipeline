export const GENERATED_BANNER =
  "<!-- Generated by `node scripts/generate-docs.mjs` — do not edit by hand. -->";

export const SKILL_CLI_BEGIN = "<!-- BEGIN GENERATED: cli-command-table -->";
export const SKILL_CLI_END = "<!-- END GENERATED: cli-command-table -->";

export function normalizeNewlines(text: string): string {
  return text.replace(/\r\n/g, "\n").replace(/\s+$/u, "") + "\n";
}

