export interface CliDocInventoryEntry {
  keyword: string;
  summary: string;
  usage: string;
  section?: string;
}

/**
 * Build the documented CLI inventory from a registry + docs map.
 * Never invents commands absent from the registry.
 */
export function buildCliInventory(
  registry: Record<string, unknown> = COMMAND_REGISTRY,
  docs: Record<string, CommandDoc> = COMMAND_DOCS,
): CliDocInventoryEntry[] {
  const keys = Object.keys(registry).filter((k) => {
    const doc = docs[k];
    if (!doc) return false;
    if (doc.documented === false) return false;
    return true;
  });
  // Preserve listDocumentedCommands order when using live sources.
  const ordered =
    registry === COMMAND_REGISTRY && docs === COMMAND_DOCS
      ? listDocumentedCommands()
      : keys.sort();
  return ordered.map((keyword) => {
    const doc = docs[keyword]!;
    return {
      keyword,
      summary: doc.summary,
      usage: doc.usage,
      section: doc.section,
    };
  });
}

/** Render host-token-agnostic usage lines with a host prefix. */
export function formatUsageLines(usage: string, hostToken: string): string[] {
  return usage
    .split("\n")
    .map((line) => line.trim())
    .filter(Boolean)
    .map((line) => {
      // Already-prefixed (shouldn't happen) or bare body.
      if (line.startsWith("/pipeline") || line.startsWith("$pipeline") || line.startsWith("pipeline ")) {
        return line.replace(/^(?:\/|\$)?pipeline/, hostToken);
      }
      // Namespaced form: "status <N>" → "/pipeline:status <N>" when first token is the keyword
      // Advance forms start with "N" or flags after N.
      if (/^N(\s|$)/.test(line) || line.startsWith("--")) {
        return `${hostToken} ${line}`;
      }
      // Subcommands: "status <N>", "config sync", "evals plan …", "loop --audit"
      const colonStyle = /^(status|unblock|override|summary|doctor|init|cleanup|intake|triage|sweep|roadmap|merge|release|logs|loop)\b/.test(
        line,
      );
      if (colonStyle) {
        // Prefer host:command for the primary synopsis line when it looks like a top-level verb.
        const m = line.match(/^(\S+)(\s+.*)?$/);
        if (m && !m[1]!.includes(" ")) {
          return `${hostToken}:${m[1]}${m[2] ?? ""}`;
        }
      }
      return `${hostToken} ${line}`;
    });
}

export function renderCliReferenceMarkdown(
  inventory: CliDocInventoryEntry[] = buildCliInventory(),
): string {
  const lines: string[] = [
    "# CLI reference",
    "",
    GENERATED_BANNER,
    "",
    "Generated from `COMMAND_REGISTRY` + `COMMAND_DOCS` (see `core/scripts/command-registry.ts`",
    "and `core/scripts/command-docs.ts`). Host skill command tables are fed from the same inventory.",
    "",
    "Invoke via the host skill (`/pipeline` in Claude Code, `$pipeline` in Codex) or the",
    "`pipeline` CLI launcher after install. Usage lines below use the neutral `pipeline` token;",
    "substitute your host form as needed.",
    "",
    "| Command | Summary |",
    "| --- | --- |",
  ];

  for (const entry of inventory) {
    const firstUsage = entry.usage.split("\n")[0]!.trim();
    const cmdCell = firstUsage.startsWith("N")
      ? `\`pipeline ${firstUsage}\``
      : `\`pipeline ${firstUsage}\``;
    // Escape pipes in summary.
    const summary = entry.summary.replace(/\|/g, "\\|");
    lines.push(`| ${cmdCell} | ${summary} |`);
  }

  lines.push("", "## Commands", "");

  for (const entry of inventory) {
    lines.push(`### \`${entry.keyword}\``, "");
    lines.push(entry.summary, "");
    lines.push("```text");
    for (const u of formatUsageLines(entry.usage, "pipeline")) {
      lines.push(u);
    }
    lines.push("```", "");
  }

  lines.push(
    "## Notes",
    "",
    "- Legacy alias `run` (equivalent to advance without detach) is dispatch-only and omitted here.",
    "- Agent-only `papercut` is hidden from operator docs; see OpenSpec / improve auto-file paths.",
    "- There is no `auto_merge` config key and the advance loop never merges; use `pipeline merge <pr>` only as a human action after `pipeline:ready-to-deploy`.",
    "",
  );

  return normalizeNewlines(lines.join("\n"));
}

/**
 * Render the fenced command-table region body for a host SKILL.md
 * (content between markers, not including the markers themselves).
 */
export function renderSkillCommandTable(
  hostToken: "/pipeline" | "$pipeline",
  inventory: CliDocInventoryEntry[] = buildCliInventory(),
): string {
  const lines: string[] = ["```"];
  for (const entry of inventory) {
    for (const u of formatUsageLines(entry.usage, hostToken)) {
      // Pad roughly like the hand-authored tables (command left, summary right).
      const pad = Math.max(2, 42 - u.length);
      lines.push(`${u}${" ".repeat(pad)}${entry.summary}`);
    }
    // Blank line between command groups for scanability.
    lines.push("");
  }
  // Drop trailing blank inside the fence.
  while (lines.length > 1 && lines[lines.length - 1] === "") lines.pop();
  lines.push("```");
  return lines.join("\n");
}

/**
 * Replace the generated region in a SKILL.md body. Returns null if markers are missing.
 */
export function replaceSkillGeneratedRegion(
  skillBody: string,
  generatedInner: string,
): string | null {
  const begin = skillBody.indexOf(SKILL_CLI_BEGIN);
  const end = skillBody.indexOf(SKILL_CLI_END);
  if (begin < 0 || end < 0 || end < begin) return null;
  const before = skillBody.slice(0, begin + SKILL_CLI_BEGIN.length);
  const after = skillBody.slice(end);
  // Ensure single newlines around the region body.
  const body = generatedInner.replace(/^\n+|\n+$/g, "");
  return `${before}\n${body}\n${after}`;
}

